#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const guides = JSON.parse(fs.readFileSync(path.join(root, 'data/guides.json'), 'utf8')).guides.filter((guide) => guide.status === 'live');
const rows = guides.map((guide) => {
  const file = path.join(root, 'main-site/guides', `${guide.slug}.html`);
  const html = fs.readFileSync(file, 'utf8');
  const browser = (html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] || '').replace(/&amp;/g, '&').replace(/<[^>]+>/g, '').trim();
  const gate = html.includes('/assets/guide-gate.js') || ['ai-jargon-guide', 'what-is-ai'].includes(guide.slug) ? 'Configured' : 'Missing';
  const differences = [];
  if (guide.title !== guide.h1) differences.push('Directory title and H1 differ');
  if (browser && !browser.toLowerCase().includes(guide.h1.toLowerCase().slice(0, 24))) differences.push('Browser title and H1 may differ');
  return `| \`${guide.slug}\` | ${guide.title} | ${browser || 'Generated by Next.js'} | ${guide.h1} | ${guide.summary || 'No directory summary'} | ${gate} | Active | Awaiting Fatiha review | ${differences.join('; ') || 'None detected'} |`;
});

const document = `# Guide copy review queue\n\nThis is an inventory, not a rewrite. Individual guide bodies remain for Fatiha to review one by one.\n\n| Slug | Directory card title | Browser title | H1 | Summary | Email gate | Public status | Copy-review status | Inconsistency |\n|---|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n\n## SEO notes for Fatiha\n\nReview search phrasing only when you review each guide. Do not insert keywords into a guide solely for ranking. Useful natural-language themes include AI for work, AI tools for business, AI automation, AI agents, ChatGPT for business, Claude vs ChatGPT, how to write AI prompts and automate repetitive work.\n`;
fs.writeFileSync(path.join(root, 'docs/GUIDE-COPY-REVIEW-QUEUE.md'), document);
console.log(`Recorded ${guides.length} public guides in the review queue.`);
